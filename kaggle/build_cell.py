"""Build kaggle/lt_cell.py: one notebook cell that writes the lt package and runs lt.train.

    python kaggle/build_cell.py          # regenerate after changing lt/

The cell embeds lt/{__init__,model,kernel,data,train}.py verbatim, writes them under /kaggle/working/lt_src, saves
CFG as JSON and launches `python -m lt.train` (torchrun with one process per GPU when there are several).
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULES = ('__init__.py', 'model.py', 'kernel.py', 'data.py', 'train.py')

HEADER = '''# -*- coding: utf-8 -*-
# LT bounded phase-clock STDP -- Kaggle single cell. GENERATED by kaggle/build_cell.py from lt/; do not edit here.
# Paste the whole file into ONE notebook cell and run it. Settings: CFG below (overrides of lt.train.DEFAULTS).
# Data: attach sudoku_lt_1k.npz as an Input (searched under /kaggle/input if CFG['data_npz'] is missing).
# Rerunning the cell resumes from the latest step_*.pt in out_dir; for a new session attach the previous output as an
# Input and set CFG['resume_from'] to that folder. max_steps is an absolute stopping step.
CFG = {
    'outer_rho': 0.5,              # model B: W <- rho W + Im S. 0.0 = model A (run A of 2026-10-14)
    'alpha_init': 1.0,
    'data_npz': '/kaggle/input/datasets/jrjinwoo/sudoku-lt-1k/sudoku_lt_1k.npz',
    'out_dir': '/kaggle/working/lt_run',
    'resume_from': None,
    'max_steps': 50800,
    'max_hours': 11.5,             # save and stop cleanly before the session limit
    'save_every_steps': 2000,
    'keep_last': 2,
    'milestone_every': 10000,      # keep a checkpoint and run the 128-segment extrapolation every 10k steps
    'log_every': 250,
}

import json, os, subprocess, sys
from pathlib import Path
'''

FOOTER = '''

def _launch():
    import torch
    cfg = dict(CFG)
    if cfg.get('data_npz') and not Path(cfg['data_npz']).is_file():
        cfg['data_npz'] = None
    root = Path('/kaggle/working/lt_src' if Path('/kaggle/working').is_dir() else 'lt_src').resolve()
    for name, source in SOURCES.items():
        path = root / 'lt' / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source)
    (root / 'run.json').write_text(json.dumps(cfg, indent=1))
    n = torch.cuda.device_count()
    cmd = ([sys.executable, '-m', 'torch.distributed.run', '--standalone', f'--nproc_per_node={n}'] if n > 1
           else [sys.executable]) + ['-m', 'lt.train', '--config', str(root / 'run.json')]
    print('[cell]', ' '.join(cmd), flush=True)
    proc = subprocess.Popen(cmd, cwd=root, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, bufsize=1)
    for line in proc.stdout:
        print(line, end='', flush=True)
    if proc.wait():
        raise RuntimeError(f'training exited with code {proc.returncode}')


_launch()
'''


def main():
    sources = {name: (ROOT / 'lt' / name).read_text() for name in MODULES}
    body = 'SOURCES = {\n' + ''.join(f'    {name!r}: {src!r},\n' for name, src in sources.items()) + '}\n'
    out = ROOT / 'kaggle' / 'lt_cell.py'
    out.write_text(HEADER + '\n' + body + FOOTER)
    print('wrote', out)


if __name__ == '__main__':
    main()
